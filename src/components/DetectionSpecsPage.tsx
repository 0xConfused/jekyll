import React, { useState, useMemo, useRef, useEffect, useCallback } from 'react';
import {
  ShieldAlert,
  Copy,
  Check,
  ChevronLeft,
  ChevronRight,
} from 'lucide-react';
import { PROFILE_DETECTION_SPECS, ProfileDetectionSpec } from '../data/detectionRules';
import { HighlightedYara } from './HighlightedYara';
import { EngineProfile } from '../types';
import { getAllEngineProfiles, DEFAULT_ENGINE_ID } from '../engines';

interface DetectionSpecsPageProps {
  profiles?: EngineProfile[];
  selectedProfileId?: string;
  initialProfileId?: string;
  onSelectProfile?: (id: string) => void;
  onBackToCompiler?: () => void;
}

export const DetectionSpecsPage: React.FC<DetectionSpecsPageProps> = ({
  profiles = getAllEngineProfiles(),
  selectedProfileId,
  initialProfileId = DEFAULT_ENGINE_ID,
  onSelectProfile,
}) => {
  const [selectedId, setSelectedId] = useState<string>(
    selectedProfileId || initialProfileId
  );
  const [copiedKey, setCopiedKey] = useState<string | null>(null);

  // Keep internal selectedId in sync with incoming selectedProfileId
  useEffect(() => {
    if (selectedProfileId && selectedProfileId !== selectedId) {
      setSelectedId(selectedProfileId);
    }
  }, [selectedProfileId, selectedId]);

  const handleSelectId = (id: string) => {
    setSelectedId(id);
    onSelectProfile?.(id);
  };

  const spec: ProfileDetectionSpec = useMemo(() => {
    if (PROFILE_DETECTION_SPECS[selectedId]) {
      return PROFILE_DETECTION_SPECS[selectedId];
    }
    const matchedProfile = profiles.find((p) => p.id === selectedId);
    const label = matchedProfile?.label || selectedId;
    const desc = matchedProfile?.description || 'This engine injects a custom JavaScript payload.';
    const safeRuleName = `Detect_${selectedId.replace(/\W/g, '_')}`;

    return {
      profileId: selectedId,
      profileLabel: label,
      title: `${label} Payload Detection`,
      category: 'Client-Side Infiltration / Script Injection',
      severity: 'MEDIUM',
      mitreTechnique: 'T1059.007',
      mitreTactics: ['Execution', 'Defense Evasion'],
      summary: `Automated detection specifications for ${label} (${selectedId}): ${desc}.`,
      detectionStrategy:
        'Evaluated against HTML documents. Confluent correlation of HTML carrier tokens, decode mechanics, and execution sinks offsets false positive risk on benign pages.',
      yaraRule: {
        ruleName: safeRuleName,
        description: `Detects artifacts generated via ${label}`,
        code: `rule ${safeRuleName}
{
    strings:
        $doctype="<!DOCTYPE html>" nocase
        $script_tag="<script" nocase
        $sink_eval=/eval\\s*\\(/ ascii
        $sink_timeout=/setTimeout\\s*\\(/ ascii
        $sink_interval=/setInterval\\s*\\(/ ascii
        $sink_func=/Function\\s*\\(/ ascii

    condition:
        $doctype and $script_tag and (any of ($sink_*) or filesize < 5000000)
}`,
      },
      regexDetections: [
        {
          id: `rgx-${selectedId}-01`,
          name: `${label} Script Tag & Dynamic Sink Identifier`,
          role: 'CONFLUENT_SUM',
          pattern: `<script[^>]*>[\\s\\S]*?(?:eval|setTimeout|setInterval|Function)\\s*\\([\\s\\S]*?<\\/script>`,
          flags: 'gmi',
          flavor: 'ECMAScript',
          description: `Anchored on static <script; matches script injection blocks generated by ${label} targeting dynamic execution sinks.`,
          sampleMatch: `<script>setTimeout(function(){ ... }, 0);</script>`,
        },
      ],
      siemDetections: [
        {
          platform: 'Sigma',
          query: `title: ${label} HTML Artifact Generation
status: experimental
description: Detects artifact generation from ${label}
logsource:
  category: file_event
detection:
  selection:
    TargetFilename|endswith: '.html'
  condition: selection`,
        },
      ],
      mitigationAdvice: `Review artifacts compiled by ${label}. Implement strict Content-Security-Policy (CSP) headers with cryptographic SHA-256 script hashes to prevent unauthorized inline script execution.`,
    };
  }, [selectedId, profiles]);

  const handleCopy = (text: string, key: string) => {
    navigator.clipboard.writeText(text);
    setCopiedKey(key);
    setTimeout(() => {
      setCopiedKey(null);
    }, 2000);
  };

  // Derive selector items: all registered profiles (in alphabetical order)
  const selectorItems = profiles.length > 0
    ? profiles
    : Object.values(PROFILE_DETECTION_SPECS)
        .map((s) => ({
          id: s.profileId,
          label: s.profileLabel,
          description: s.summary,
          defaultOutputName: '{{filehash}}.html',
        }))
        .sort((a, b) => a.label.localeCompare(b.label, undefined, { sensitivity: 'base' }));

  const scrollContainerRef = useRef<HTMLDivElement>(null);
  const [canScrollLeft, setCanScrollLeft] = useState(false);
  const [canScrollRight, setCanScrollRight] = useState(false);

  const updateScrollButtons = useCallback(() => {
    const el = scrollContainerRef.current;
    if (!el) return;
    setCanScrollLeft(el.scrollLeft > 2);
    setCanScrollRight(el.scrollLeft < el.scrollWidth - el.clientWidth - 2);
  }, []);

  useEffect(() => {
    updateScrollButtons();
    const el = scrollContainerRef.current;
    if (!el) return;
    el.addEventListener('scroll', updateScrollButtons, { passive: true });
    window.addEventListener('resize', updateScrollButtons);
    return () => {
      el.removeEventListener('scroll', updateScrollButtons);
      window.removeEventListener('resize', updateScrollButtons);
    };
  }, [updateScrollButtons, selectorItems]);

  // Scroll into view whenever active selection changes
  useEffect(() => {
    const el = scrollContainerRef.current;
    if (!el) return;
    const activeBtn = el.querySelector<HTMLButtonElement>('[data-active="true"]');
    if (activeBtn) {
      activeBtn.scrollIntoView({ behavior: 'smooth', block: 'nearest', inline: 'nearest' });
    }
  }, [selectedId]);

  const scrollByEntry = (direction: 'left' | 'right') => {
    const el = scrollContainerRef.current;
    if (!el) return;
    const children = Array.from(el.children) as HTMLElement[];
    const scrollDistance = Math.max(450, Math.floor(el.clientWidth * 0.8));

    if (children.length > 0) {
      const targetScroll =
        direction === 'right'
          ? el.scrollLeft + scrollDistance
          : Math.max(0, el.scrollLeft - scrollDistance);

      // Find closest child to targetScroll to align cleanly to an item
      const targetChild = children.reduce((closest, child) => {
        return Math.abs(child.offsetLeft - targetScroll) <
          Math.abs(closest.offsetLeft - targetScroll)
          ? child
          : closest;
      }, children[0]);

      if (targetChild) {
        el.scrollTo({ left: targetChild.offsetLeft, behavior: 'smooth' });
        return;
      }
    }

    el.scrollBy({
      left: direction === 'right' ? scrollDistance : -scrollDistance,
      behavior: 'smooth',
    });
  };

  return (
    <div className="w-full flex flex-col gap-6 animate-in fade-in duration-200">
      {/* Profile Selector Strip: Single row with arrow controls on both ends and no scrollbar */}
      <div className="bg-[#141414] border border-[#383838] p-1 flex items-center gap-1.5 w-full">
        {/* Left scroll arrow */}
        <button
          type="button"
          onClick={() => scrollByEntry('left')}
          disabled={!canScrollLeft}
          title="Scroll left"
          aria-label="Scroll left"
          className={`h-8 px-2 flex items-center justify-center border transition-colors shrink-0 ${
            canScrollLeft
              ? 'bg-[#1a1a1a] hover:bg-[#262626] text-[#f0f0f0] border-[#383838] hover:border-[#c30800] cursor-pointer'
              : 'bg-[#141414] text-[#737373] border-transparent opacity-30 cursor-not-allowed'
          }`}
        >
          <ChevronLeft className="w-4 h-4" />
        </button>

        {/* Scrollable single-row track with hidden scrollbar */}
        <div
          ref={scrollContainerRef}
          className="flex-1 flex items-center gap-1.5 overflow-x-auto scroll-smooth py-0.5 [scrollbar-width:none] [-ms-overflow-style:none] [&::-webkit-scrollbar]:hidden"
        >
          {selectorItems.map((item) => {
            const isActive = item.id === selectedId;
            return (
              <button
                key={item.id}
                type="button"
                data-active={isActive ? 'true' : 'false'}
                onClick={() => handleSelectId(item.id)}
                className={`px-3 py-2 text-xs font-mono tracking-wider transition-all flex items-center gap-2 cursor-pointer shrink-0 whitespace-nowrap ${
                  isActive
                    ? 'bg-[#262626] text-[#f3f3f7] border border-[#c30800] shadow-sm font-bold'
                    : 'bg-[#1a1a1a] text-[#8c8c8c] border border-transparent hover:text-[#f0f0f0] hover:bg-[#202020]'
                }`}
              >
                <span className="font-mono tracking-wider">{item.label}</span>
              </button>
            );
          })}
        </div>

        {/* Right scroll arrow */}
        <button
          type="button"
          onClick={() => scrollByEntry('right')}
          disabled={!canScrollRight}
          title="Scroll right"
          aria-label="Scroll right"
          className={`h-8 px-2 flex items-center justify-center border transition-colors shrink-0 ${
            canScrollRight
              ? 'bg-[#1a1a1a] hover:bg-[#262626] text-[#f0f0f0] border-[#383838] hover:border-[#c30800] cursor-pointer'
              : 'bg-[#141414] text-[#737373] border-transparent opacity-30 cursor-not-allowed'
          }`}
        >
          <ChevronRight className="w-4 h-4" />
        </button>
      </div>

      {/* Main Spec Content (Full Width) */}
      <div className="w-full flex flex-col gap-6">
        {/* Header Profile Spec Card */}
        <div className="bg-[#141414] border border-[#383838] overflow-hidden">
          <div className="h-[2px] w-full bg-gradient-to-r from-[#c30800] via-[#c300bb] to-[#bbc300]" />
          <div className="p-4 sm:p-5 bg-gradient-to-r from-[#c30800]/10 via-transparent to-transparent flex flex-col">
            <h2 className="text-base sm:text-lg font-bold text-[#f0f0f0] tracking-wide">
              {spec.title}
            </h2>
            <p className="text-xs sm:text-sm font-sans text-[#8c8c8c] mt-1.5 leading-relaxed">
              {spec.summary}
            </p>
          </div>
        </div>


        {/* YARA Detection Specification Card */}
        <div className="bg-[#141414] border border-[#383838] flex flex-col">
          <div className="px-4 py-3 bg-[#1a1a1a] border-b border-[#383838] flex flex-wrap items-center justify-between gap-2">
            <div className="flex items-center gap-2">
              <ShieldAlert className="w-4 h-4 text-[#c30800]" />
              <h3 className="text-xs font-mono font-bold text-[#f0f0f0] uppercase tracking-wider">
                RECOMMENDED YARA RULE
              </h3>
            </div>

            <div className="flex items-center gap-2">
              <button
                type="button"
                onClick={() => handleCopy(spec.yaraRule.code, 'yara')}
                className="btn btn-secondary py-1 px-3 text-xs font-mono flex items-center gap-1.5 cursor-pointer border-[#383838] hover:border-[#c30800]"
              >
                {copiedKey === 'yara' ? (
                  <>
                    <Check className="w-3.5 h-3.5 text-[#bbc300]" />
                    <span className="text-[#bbc300]">COPIED</span>
                  </>
                ) : (
                  <>
                    <Copy className="w-3.5 h-3.5 text-[#8c8c8c]" />
                    <span>COPY</span>
                  </>
                )}
              </button>
            </div>
          </div>

          <div className="p-4 bg-[#0d0d0d] overflow-x-auto">
            <pre className="text-xs font-mono text-[#f0f0f0] leading-relaxed selection:bg-[#c30800] selection:text-[#f3f3f7]">
              <code>
                <HighlightedYara code={spec.yaraRule.code} />
              </code>
            </pre>
          </div>
        </div>
      </div>
    </div>
  );
};
