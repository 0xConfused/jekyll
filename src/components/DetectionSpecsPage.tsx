import React, { useState, useMemo } from 'react';
import {
  ShieldAlert,
  Copy,
  Check,
  FileCode,
  Terminal,
} from 'lucide-react';
import { PROFILE_DETECTION_SPECS, ProfileDetectionSpec } from '../data/detectionRules';
import { EngineProfile } from '../types';
import { getAllEngineProfiles } from '../engines';

interface DetectionSpecsPageProps {
  profiles?: EngineProfile[];
  initialProfileId?: string;
  onBackToCompiler?: () => void;
}

export const DetectionSpecsPage: React.FC<DetectionSpecsPageProps> = ({
  profiles = getAllEngineProfiles(),
  initialProfileId = 'url-matrix',
}) => {
  const [selectedId, setSelectedId] = useState<string>(initialProfileId);
  const [copiedKey, setCopiedKey] = useState<string | null>(null);

  const spec: ProfileDetectionSpec = useMemo(() => {
    if (PROFILE_DETECTION_SPECS[selectedId]) {
      return PROFILE_DETECTION_SPECS[selectedId];
    }
    const matchedProfile = profiles.find((p) => p.id === selectedId);
    const label = matchedProfile?.label || selectedId;
    const desc = matchedProfile?.description || 'Custom JavaScript injection engine';
    const safeRuleName = `Detect_${selectedId.replace(/[^a-zA-Z0-9_]/g, '_')}`;

    return {
      profileId: selectedId,
      profileLabel: label,
      title: `${label} Payload Detection`,
      category: 'Client-Side Infiltration / Script Injection',
      severity: 'MEDIUM',
      mitreTechnique: 'T1059.007',
      mitreTactics: ['Execution', 'Defense Evasion'],
      summary: `Automated detection specifications for ${label} (${selectedId}): ${desc}.`,
      yaraRule: {
        ruleName: safeRuleName,
        description: `Detects artifacts generated via ${label}`,
        code: `rule ${safeRuleName}
{
    meta:
        author = "0xCONFUSED Cyber Operations"
        description = "Detects standalone artifacts generated via ${label}"
        severity = "MEDIUM"
        mitre_technique = "T1059.007"
        date = "2026-10-12"
        license = "AGPL-3.0-or-later"

    strings:
        $doctype = "<!DOCTYPE html>" nocase
        $script_tag = "<script" nocase
        $engine_marker = "${selectedId}"

    condition:
        $doctype and $script_tag and ($engine_marker or filesize < 5000000)
}`,
      },
      regexDetections: [
        {
          id: `rgx-${selectedId}-01`,
          name: `${label} Script Tag Identifier`,
          pattern: `<script[^>]*>[\\s\\S]*?<\\/script>`,
          flags: 'gmi',
          flavor: 'ECMAScript',
          description: `Matches script injection blocks generated by ${label}`,
          sampleMatch: `<script type="text/javascript">/* Injected */</script>`,
        },
      ],
      siemDetections: [
        {
          platform: 'Sigma',
          query: `title: ${label} HTML Artifact Generation
status: experimental
description: Detects artifact generation from ${label}
logsource:
  category: file_event
detection:
  selection:
    TargetFilename|endswith: '.html'
  condition: selection`,
        },
      ],
      mitigationAdvice: `Review artifacts compiled by ${label}. Implement strict Content-Security-Policy (CSP) headers with cryptographic SHA-256 script hashes to prevent unauthorized inline script execution.`,
    };
  }, [selectedId, profiles]);

  const handleCopy = (text: string, key: string) => {
    navigator.clipboard.writeText(text);
    setCopiedKey(key);
    setTimeout(() => {
      setCopiedKey(null);
    }, 2000);
  };

  // Derive selector items: all registered profiles
  const selectorItems = profiles.length > 0 ? profiles : Object.values(PROFILE_DETECTION_SPECS).map(s => ({
    id: s.profileId,
    label: s.profileLabel,
    description: s.summary,
    defaultOutputName: '{{filehash}}.html',
  }));

  return (
    <div className="w-full flex flex-col gap-6 animate-in fade-in duration-200">
      {/* Profile Selector Strip */}
      <div className="bg-[#141414] border border-[#383838] p-1.5 flex flex-wrap gap-1.5">
        {selectorItems.map((item) => {
          const isActive = item.id === selectedId;
          return (
            <button
              key={item.id}
              type="button"
              onClick={() => setSelectedId(item.id)}
              className={`px-3 py-2 text-xs font-mono tracking-wider transition-all flex items-center gap-2 cursor-pointer ${
                isActive
                  ? 'bg-[#262626] text-[#f3f3f7] border border-[#c30800] shadow-sm font-bold'
                  : 'bg-[#1a1a1a] text-[#8c8c8c] border border-transparent hover:text-[#f0f0f0] hover:bg-[#202020]'
              }`}
            >
              <span>{item.label}</span>
            </button>
          );
        })}
      </div>

      {/* Main Spec Content (Full Width) */}
      <div className="w-full flex flex-col gap-6">
        {/* Header Profile Spec Card */}
        <div className="bg-[#141414] border border-[#383838] overflow-hidden">
          <div className="h-[2px] w-full bg-gradient-to-r from-[#c30800] via-[#c300bb] to-[#bbc300]" />
          <div className="p-4 sm:p-5 bg-gradient-to-r from-[#c30800]/10 via-transparent to-transparent flex flex-col">
            <h2 className="text-base sm:text-lg font-bold text-[#f0f0f0] tracking-wide">
              {spec.title}
            </h2>
            <p className="text-xs sm:text-sm font-sans text-[#8c8c8c] mt-1.5 leading-relaxed">
              {spec.summary}
            </p>
          </div>
        </div>

        {/* YARA Detection Specification Card */}
        <div className="bg-[#141414] border border-[#383838] flex flex-col">
          <div className="px-4 py-3 bg-[#1a1a1a] border-b border-[#383838] flex flex-wrap items-center justify-between gap-2">
            <div className="flex items-center gap-2">
              <ShieldAlert className="w-4 h-4 text-[#c30800]" />
              <h3 className="text-xs font-mono font-bold text-[#f0f0f0] uppercase tracking-wider">
                RECOMMENDED YARA RULE
              </h3>
            </div>

            <div className="flex items-center gap-2">
              <button
                type="button"
                onClick={() => handleCopy(spec.yaraRule.code, 'yara')}
                className="btn btn-secondary py-1 px-3 text-xs font-mono flex items-center gap-1.5 cursor-pointer border-[#383838] hover:border-[#c30800]"
              >
                {copiedKey === 'yara' ? (
                  <>
                    <Check className="w-3.5 h-3.5 text-[#bbc300]" />
                    <span className="text-[#bbc300]">COPIED</span>
                  </>
                ) : (
                  <>
                    <Copy className="w-3.5 h-3.5 text-[#8c8c8c]" />
                    <span>COPY</span>
                  </>
                )}
              </button>
            </div>
          </div>

          <div className="p-4 bg-[#0d0d0d] overflow-x-auto">
            <pre className="text-xs font-mono text-[#f0f0f0] leading-relaxed selection:bg-[#c30800] selection:text-[#f3f3f7]">
              <code>{spec.yaraRule.code}</code>
            </pre>
          </div>
        </div>

        {/* Regex Detection Rules Card */}
        <div className="bg-[#141414] border border-[#383838] flex flex-col">
          <div className="px-4 py-3 bg-[#1a1a1a] border-b border-[#383838] flex items-center justify-between">
            <div className="flex items-center gap-2">
              <FileCode className="w-4 h-4 text-[#c30800]" />
              <h3 className="text-xs font-mono font-bold text-[#f0f0f0] uppercase tracking-wider">
                RECOMMENDED REGEX DETECTION SIGNATURES
              </h3>
            </div>
            <span className="text-[10px] font-mono text-[#8c8c8c]">
              {spec.regexDetections.length} SIGNATURES
            </span>
          </div>

          <div className="divide-y divide-[#2e2e2e]">
            {spec.regexDetections.map((rd) => {
              const copyKey = `regex-${rd.id}`;
              return (
                <div key={rd.id} className="p-4 flex flex-col gap-2.5 bg-[#141414] hover:bg-[#181818] transition-colors">
                  <div className="flex flex-wrap items-center justify-between gap-2">
                    <div className="flex items-center gap-2">
                      <span className="w-1.5 h-1.5 bg-[#c30800]" />
                      <h4 className="text-xs font-mono font-bold text-[#f0f0f0]">
                        {rd.name}
                      </h4>
                    </div>

                    <button
                      type="button"
                      onClick={() => handleCopy(rd.pattern, copyKey)}
                      className="btn btn-secondary py-1 px-2.5 text-xs font-mono flex items-center gap-1.5 cursor-pointer border-[#383838] hover:border-[#c30800]"
                    >
                      {copiedKey === copyKey ? (
                        <>
                          <Check className="w-3.5 h-3.5 text-[#bbc300]" />
                          <span className="text-[#bbc300]">COPIED</span>
                        </>
                      ) : (
                        <>
                          <Copy className="w-3.5 h-3.5 text-[#8c8c8c]" />
                          <span>COPY REGEX</span>
                        </>
                      )}
                    </button>
                  </div>

                  <p className="text-[11px] font-sans text-[#8c8c8c]">
                    {rd.description}
                  </p>

                  <div className="bg-[#0d0d0d] border border-[#2e2e2e] p-2.5 font-mono text-xs overflow-x-auto text-[#f0f0f0]">
                    <span className="text-[#737373] select-none">/</span>
                    <span className="text-[#f0f0f0] font-semibold">{rd.pattern}</span>
                    <span className="text-[#737373] select-none">/{rd.flags}</span>
                  </div>
                </div>
              );
            })}
          </div>
        </div>

        {/* SIEM & Sigma Queries Card */}
        {spec.siemDetections.length > 0 && (
          <div className="bg-[#141414] border border-[#383838] flex flex-col">
            <div className="px-4 py-3 bg-[#1a1a1a] border-b border-[#383838] flex items-center justify-between">
              <div className="flex items-center gap-2">
                <Terminal className="w-4 h-4 text-[#c30800]" />
                <h3 className="text-xs font-mono font-bold text-[#f0f0f0] uppercase tracking-wider">
                  SIEM &amp; SIGMA LOG DETECTION QUERIES
                </h3>
              </div>
            </div>

            <div className="divide-y divide-[#2e2e2e]">
              {spec.siemDetections.map((sd, i) => {
                const copyKey = `siem-${i}`;
                return (
                  <div key={i} className="p-4 flex flex-col gap-2">
                    <div className="flex items-center justify-between">
                      <span className="text-xs font-mono font-bold text-[#f0f0f0]">
                        {sd.platform} Query Format
                      </span>
                      <button
                        type="button"
                        onClick={() => handleCopy(sd.query, copyKey)}
                        className="btn btn-secondary py-1 px-2.5 text-xs font-mono flex items-center gap-1.5 cursor-pointer border-[#383838] hover:border-[#c30800]"
                      >
                        {copiedKey === copyKey ? (
                          <>
                            <Check className="w-3.5 h-3.5 text-[#bbc300]" />
                            <span className="text-[#bbc300]">COPIED</span>
                          </>
                        ) : (
                          <>
                            <Copy className="w-3.5 h-3.5 text-[#8c8c8c]" />
                            <span>COPY QUERY</span>
                          </>
                        )}
                      </button>
                    </div>
                    <div className="bg-[#0d0d0d] p-3 border border-[#2e2e2e] overflow-x-auto">
                      <pre className="text-xs font-mono text-[#8c8c8c] whitespace-pre-wrap">
                        <code>{sd.query}</code>
                      </pre>
                    </div>
                  </div>
                );
              })}
            </div>
          </div>
        )}
      </div>
    </div>
  );
};
